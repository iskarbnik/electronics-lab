import { T, info, wire, place, toggle, quiz, batterySetup } from './common.js';
import { inputA, inputB, outChain, adderSchematic } from './logic.js';

export default {
  id: 'l16-half-adder',
  unit: 2,
  title: T('חצי מחבר: חיבור בבינארי', 'The half adder: adding in binary'),
  summary: T('שני שערים שמחברים שני ביטים: XOR לסכום ו-AND לנשא.', 'Two gates that add two bits: XOR for the sum and AND for the carry.'),
  schematic: adderSchematic(),
  setup: [...batterySetup(), ...inputA(), ...inputB(), ...outChain(1), ...outChain(2)],
  steps: [
    info(T(
      'מחשב מחבר מספרים בעזרת שערים. חצי מחבר מחבר שני ביטים, A ו-B, ונותן שני מוצאים: סכום (נורית ירוקה) ונשא (נורית צהובה). בבינארי 1 + 1 הוא 10: הסכום 0 והנשא 1.',
      'A computer adds numbers with gates. A half adder adds two bits, A and B, and gives two outputs: a sum (green LED) and a carry (yellow LED). In binary 1 + 1 is 10: the sum is 0 and the carry is 1.')),
    place('G1', 'gate', ['j6', 'j7', 'j8'], { fn: 'xor' },
      T('הציבו שער XOR בעמודות 6, 7 ו-8. הוא ייתן את הסכום.', 'Place an XOR gate in columns 6, 7 and 8. It will give the sum.')),
    place('G2', 'gate', ['j13', 'j14', 'j15'], { fn: 'and' },
      T('הציבו שער AND בעמודות 13, 14 ו-15. הוא ייתן את הנשא.', 'Place an AND gate in columns 13, 14 and 15. It will give the carry.')),
    wire('XA1', ['e4', 'f6'], 'blue',
      T('חברו את מתג A (עמודה 4) לכניסה A של ה-XOR (עמודה 6).', 'Connect switch A (column 4) to input A of the XOR (column 6).')),
    wire('XB1', ['e10', 'f7'], 'yellow',
      T('חברו את מתג B (עמודה 10) לכניסה B של ה-XOR (עמודה 7).', 'Connect switch B (column 10) to input B of the XOR (column 7).')),
    wire('XA2', ['d4', 'f13'], 'blue',
      T('חברו את A גם לכניסה A של ה-AND (עמודה 13). אות אחד יכול להזין כמה שערים.', 'Connect A to input A of the AND (column 13) too. One signal can feed several gates.')),
    wire('XB2', ['d10', 'f14'], 'yellow',
      T('וחברו את B לכניסה B של ה-AND (עמודה 14).', 'And connect B to input B of the AND (column 14).')),
    wire('XS', ['f8', 'e18'], 'green',
      T('חברו את מוצא ה-XOR (עמודה 8) לנורית הסכום (עמודה 18).', 'Connect the XOR output (column 8) to the sum LED (column 18).')),
    wire('XC', ['f15', 'e24'], 'orange',
      T('חברו את מוצא ה-AND (עמודה 15) לנורית הנשא (עמודה 24). 0 + 0 = 00, ושתי הנוריות כבויות.', 'Connect the AND output (column 15) to the carry LED (column 24). 0 + 0 = 00, and both LEDs are off.'),
      { expect: sim => !sim.comps.D1.lit && !sim.comps.D2.lit }),
    toggle('SA', true,
      T('סגרו את A: 1 + 0 = 01. נורית הסכום דולקת והנשא כבוי.', 'Close A: 1 + 0 = 01. The sum LED is lit and the carry is off.'),
      { expect: sim => sim.comps.D1.lit && !sim.comps.D2.lit }),
    toggle('SB', true,
      T('סגרו גם את B: 1 + 1 = 10. הסכום כבה והנשא נדלק.', 'Close B too: 1 + 1 = 10. The sum goes out and the carry lights up.'),
      { expect: sim => !sim.comps.D1.lit && sim.comps.D2.lit }),
    toggle('SA', false,
      T('פתחו את A: 0 + 1 = 01. שוב הסכום דולק והנשא כבוי.', 'Open A: 0 + 1 = 01. The sum is lit again and the carry is off.'),
      { expect: sim => sim.comps.D1.lit && !sim.comps.D2.lit }),
    info(T(
      'עם שני שערים בלבד חיברנו מספרים! חיבור של מספרים גדולים הוא אותו רעיון, עם עוד שערים שמעבירים את הנשא הלאה. זה הלב של יחידת החישוב בתוך מעבד.',
      'With just two gates we added numbers! Adding bigger numbers is the same idea, with more gates passing the carry along. This is the heart of the arithmetic unit inside a processor.')),
    quiz(T('מה התוצאה של 1 + 1 בבינארי?', 'What is 1 + 1 in binary?'),
      [T('10 (סכום 0, נשא 1)', '10 (sum 0, carry 1)'), T('11', '11'), T('01', '01')], 0,
      T('שני אחדים נותנים שתיים, וזה נכתב 10 בבינארי.', 'Two ones make two, which is written 10 in binary.')),
    quiz(T('איזה שער נותן את ביט הסכום?', 'Which gate gives the sum bit?'),
      [T('XOR', 'XOR'), T('AND', 'AND'), T('NOT', 'NOT')], 0,
      T('הסכום הוא 1 כשהכניסות שונות, וזה XOR. ה-AND נותן את הנשא.', 'The sum is 1 when the inputs differ, which is XOR. The AND gives the carry.')),
  ],
};
