import { T, info, setFn, toggle, quiz, batterySetup } from './common.js';
import { inputA, inputB, outChain, gateOnBoard, linkA, linkB, linkY, gateSchematic } from './logic.js';

export default {
  id: 'l15-more-gates',
  unit: 2,
  truth: 'G1',
  title: T('NAND, NOR ו-XOR', 'NAND, NOR and XOR'),
  summary: T('שלושה שערים נוספים, על אותו מעגל בדיוק.', 'Three more gates, on exactly the same circuit.'),
  schematic: gateSchematic('and', true),
  setup: [...batterySetup(), ...inputA(), ...inputB(), ...outChain(1), gateOnBoard('and'), linkA(), linkB(), linkY(true)],
  steps: [
    info(T(
      'המעגל מוכן, עם שער AND. נשנה רק את סוג השער. NAND הוא AND עם היפוך בסוף, NOR הוא OR עם היפוך, ו-XOR נותן 1 כשהכניסות שונות זו מזו. הקישו על השער כדי לבחור את הפונקציה שלו.',
      'The circuit is ready, with an AND gate. We only change the gate type. NAND is AND with an inversion at the end, NOR is OR with an inversion, and XOR gives 1 when the inputs differ. Tap the gate to choose its function.')),
    setFn('G1', 'nand',
      T('בחרו בשער והחליפו ל-NAND. שתי הכניסות 0, ולכן המוצא 1 והנורית נדלקת.', 'Select the gate and change it to NAND. Both inputs are 0, so the output is 1 and the LED lights up.'),
      { expect: sim => sim.comps.D1.lit }),
    toggle('SA', true,
      T('סגרו את A. NAND של 1 ו-0 עדיין נותן 1.', 'Close A. NAND of 1 and 0 still gives 1.'),
      { expect: sim => sim.comps.D1.lit }),
    toggle('SB', true,
      T('סגרו גם את B. רק כששתיהן 1, ה-NAND נותן 0 והנורית כבה.', 'Close B too. Only when both are 1 does NAND give 0 and the LED goes out.'),
      { expect: sim => !sim.comps.D1.lit }),
    info(T(
      'NAND הוא ההפך המדויק של AND. הוא גם שער אוניברסלי: אפשר לבנות ממנו כל שער אחר, ולכן הוא נפוץ מאוד בתוך שבבים.',
      'NAND is the exact opposite of AND. It is also a universal gate: you can build every other gate from it, which is why it is so common inside chips.')),
    setFn('G1', 'nor',
      T('החליפו ל-NOR. שתי הכניסות 1, ולכן המוצא 0.', 'Change it to NOR. Both inputs are 1, so the output is 0.'),
      { expect: sim => !sim.comps.D1.lit }),
    toggle('SA', false,
      T('פתחו את A. NOR של 0 ו-1 הוא 0, כי מספיק אחד כדי לכבות.', 'Open A. NOR of 0 and 1 is 0, because one is enough to turn it off.'),
      { expect: sim => !sim.comps.D1.lit }),
    toggle('SB', false,
      T('פתחו גם את B. רק כששתיהן 0, ה-NOR נותן 1.', 'Open B too. Only when both are 0 does NOR give 1.'),
      { expect: sim => sim.comps.D1.lit }),
    setFn('G1', 'xor',
      T('החליפו ל-XOR. שתי הכניסות 0, ולכן המוצא 0.', 'Change it to XOR. Both inputs are 0, so the output is 0.'),
      { expect: sim => !sim.comps.D1.lit }),
    toggle('SA', true,
      T('סגרו את A בלבד. הכניסות שונות, והמוצא 1.', 'Close A only. The inputs differ, and the output is 1.'),
      { expect: sim => sim.comps.D1.lit }),
    toggle('SB', true,
      T('סגרו גם את B. הכניסות זהות, והמוצא חוזר ל-0.', 'Close B too. The inputs are the same, and the output goes back to 0.'),
      { expect: sim => !sim.comps.D1.lit }),
    info(T(
      'XOR ("או בלעדי") אומר: אחד מהם, אבל לא שניהם. זה כמו מנורה במסדרון עם שני מתגים: כל הפיכה של אחד מהם משנה את המצב. גם חיבור בינארי צריך אותו, כפי שנראה בשיעור הבא.',
      'XOR (exclusive or) means one of them, but not both. It is like a hallway lamp with two switches: flipping either one changes the state. Binary addition needs it too, as we will see in the next lesson.')),
    quiz(T('איזה שער נותן 1 בדיוק כשהכניסות שונות?', 'Which gate gives 1 exactly when the inputs differ?'),
      [T('XOR', 'XOR'), T('NOR', 'NOR'), T('NAND', 'NAND')], 0,
      T('XOR הוא "הכניסות שונות". NOR ו-NAND נותנים 1 גם כשהכניסות זהות.', 'XOR means the inputs differ. NOR and NAND also give 1 for some equal inputs.')),
    quiz(T('מתי שער NOR נותן 1?', 'When does a NOR gate give 1?'),
      [T('רק כששתי הכניסות 0', 'Only when both inputs are 0'), T('כשלפחות אחת הכניסות 1', 'When at least one input is 1'), T('רק כששתיהן 1', 'Only when both are 1')], 0,
      T('NOR הוא OR הפוך. OR נותן 0 רק כששתיהן 0, ולכן NOR נותן 1 רק אז.', 'NOR is OR inverted. OR gives 0 only when both are 0, so NOR gives 1 only then.')),
  ],
};
